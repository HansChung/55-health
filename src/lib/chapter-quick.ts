/** 沒有特別設定的章節：暖暖一題一題帶著做一次 */
export function defaultQuick(title: string): ChapterQuick {
  return {
    goal: "跟暖暖一起做一次這一節的練習",
    action: "guided",
    prompt: `我在讀「${title}」這一節，請帶我用最簡單的方式做一次練習。`,
  };
}

export function chapterQuick(id: string, title: string): ChapterQuick {
  return CHAPTER_QUICK[id] ?? defaultQuick(title);
}

/** ask／guided 實際送給暖暖的那一句（guided 加上一次一題的規則） */
export function quickPrompt(q: ChapterQuick): string {
  const text = (q.prompt ?? "").trim();
  return q.action === "guided" ? `${text}${GUIDED_SUFFIX}` : text;
}

/** 不用帶問題、直接打開的功能 → 深連結（from 讓首頁知道是從哪一章來的） */
export function quickHref(action: QuickAction, chapterId: string): string | null {
  const from = `from=chapter${chapterId}`;
  switch (action) {
    case "camera": return `/?open=camera&${from}`;
    case "voice": return `/?open=voice&${from}`;
    case "stories": return `/?open=stories&${from}`;
    case "record": return `/?open=stories&audio=1&${from}`;
    case "scam": return `/?open=scam-check&${from}`;
    case "clinic": return `/?open=clinic&${from}`;
    case "metrics": return `/?open=health-metrics&${from}`;
    case "brain": return `/?open=brain&${from}`;
    case "video": return `/?open=travel-video&${from}`;
    case "greeting": return `/?open=travel-video&mode=greeting&${from}`;
    case "tours": return `/?open=study-tours&${from}`;
    default: return null;
  }
}
