// ────────────────────────────────────────────────

export type QuickAction =
  | "ask" // 打字問暖暖（問題幫忙填好）
  | "guided" // 暖暖一次只問一題，最後幫忙整理
  | "photo" // 拍照問暖暖（問題幫忙填好）
  | "camera" // 拍照記餐
  | "voice" // 跟暖暖聊聊（語音）
  | "stories" // 我的故事集
  | "record" // 我的故事集：直接錄音
  | "scam" // 這則訊息可疑嗎？
  | "clinic" // 看診小幫手（含回診提醒）
  | "metrics" // 血壓血糖趨勢
  | "brain" // 動動腦每日一題
  | "video" // 出遊回憶影片
  | "greeting" // 祝福影片
  | "tours"; // 研學團

export interface ChapterQuick {
  /** 這一節只要做的一件事（白話，一句） */
  goal: string;
  action: QuickAction;
  /** ask／guided／photo：幫長輩填好的那一句 */
  prompt?: string;
  /** 按鈕上的字（沒寫就用 action 的預設） */
  button?: string;
}

